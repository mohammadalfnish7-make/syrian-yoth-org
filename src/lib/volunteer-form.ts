export function volunteerOptionLabel(value: string, locale: "ar" | "en"): string {
  if (locale === "en") return VOLUNTEER_OPTION_LABELS_EN[value] ?? value;
  return value;
}

/** Split a stored hobby value into a title and examples for display. */
export function volunteerHobbyDisplay(
  value: string,
  locale: "ar" | "en"
): HobbyDisplay {
  if (locale === "en" && HOBBY_LABELS_EN[value]) return HOBBY_LABELS_EN[value];
  const index = value.indexOf(":");
  if (index === -1) return { title: value, examples: "" };
  const title = value.slice(0, index).trim();
  const examples = value
    .slice(index + 1)
    .trim()
    .replace(/^\(|\)$/g, "")
    .replace(/\.$/, "")
    .replace(/^\((.*)\)$/, "$1")
    .trim();
  return { title, examples };
}

const ARABIC_DIGITS = /[٠-٩۰-۹]/g;

function toLatinDigits(value: string): string {
  return value.replace(ARABIC_DIGITS, (d) => {
    const code = d.charCodeAt(0);
    return String(code >= 0x06f0 ? code - 0x06f0 : code - 0x0660);
  });
}

/**
 * Normalize what people actually type (0912…, +963 912…, ٠٩١٢…) into the
 * 00963XXXXXXXXX form the API expects.
 */
export function normalizeVolunteerPhone(raw: string): string {
  const digits = toLatinDigits(raw).replace(/\D/g, "");
  if (!digits) return "";
  if (digits.startsWith("00963")) return digits;
  if (digits.startsWith("963")) return `00${digits}`;
  if (digits.startsWith("0")) return `00963${digits.replace(/^0+/, "")}`;
  if (digits.startsWith("9")) return `00963${digits}`;
  return digits;
}

export function isValidVolunteerPhone(phone: string): boolean {
  return /^00963\d{8,12}$/.test(phone);
}

/** Accept "username", "@username" or a t.me link and return "@username". */
export function normalizeVolunteerTelegram(raw: string): string {
  const handle = raw
    .trim()
    .replace(/^https?:\/\//i, "")
    .replace(/^(www\.)?(t|telegram)\.me\//i, "")
    .replace(/^@+/, "")
    .replace(/\/+$/, "");
  return handle ? `@${handle}` : "";
}

export function isValidVolunteerTelegram(handle: string): boolean {
  return /^@[A-Za-z0-9_]{3,}$/.test(handle);
}
